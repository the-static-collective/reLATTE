import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CompositionFieldBridge, roomSpec, routeTo, receiveCandidate, recoverHistorical, PARENTS } from './bridge.mjs';
import { LocalWorld } from '../dynamic-interface-field-001/src/world.mjs';
import { identity, signed } from '../dynamic-interface-field-001/src/history.mjs';
import { id } from '../interface-superspace-001/src/proofs.mjs';
import { occurrence, digest } from '../interface-superspace-001/src/receipts.mjs';
import { propose } from '../dynamic-interface-field-001/src/field.mjs';
import { request } from '../interface-superspace-001/src/proofs.mjs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';

export async function specimen(root) {
  mkdirSync(root, { recursive: true });
  const a = await CompositionFieldBridge.create({ root });
  const receiver = new LocalWorld({ clock: a.clock });
  const source = receiver.publish(a.library.nodes.get(id('payload-bytes')));
  const observer = a.observer({ anchors: [receiver.anchor], trust: true });
  const before = await a.discover(observer, [receiver.history(), a.fieldHistory()]);
  assert.equal(before.doors.size, 1);
  const contents = await a.runtimeTransition('open-chest');
  const eligibleView = await a.discover(observer, [receiver.history(), a.fieldHistory()]);
  const query = request(a.library, { bytes: Buffer.from('observation request'), goal: 'file.bytes', goalInterface: contents.interface_id, network: false, permissions: [contents.interface_id + '/observe'] });
  assert.equal((await propose(eligibleView, query)).status, 'NO_ROUTE');
  const doorA = a.publish(contents, a.ownerControl());
  const first = await routeTo(a, observer, receiver, source, doorA);
  const grantsA = a.authorize(first.plan, first.peers, 'visitor', a.ownerControl(), { max_uses: 3 });
  const occurrenceA = await a.execute(first.view, first.plan, first.source, { ...first, subject: 'visitor', grants: grantsA });
  assert.equal(occurrenceA.record.result, 'succeeded');
  const map = await a.runtimeTransition('reveal-map');
  const doorB = a.publish(map, a.ownerControl());
  assert.equal(doorB.parents[0].offer_id, doorA.offer_id);
  const second = await routeTo(a, observer, receiver, source, doorB);
  const grantsB = a.authorize(second.plan, second.peers, 'visitor', a.ownerControl());
  const occurrenceB = await a.execute(second.view, second.plan, second.source, { ...second, subject: 'visitor', grants: grantsB });
  assert.equal(occurrenceB.record.result, 'succeeded');
  a.observe();
  const checkpoint = a.snapshot(a.ownerControl());
  const produced = await a.candidate();
  const candidateBefore = digest(a.store.get(produced.candidate_ref));
  const historicalA = a.evidence();
  await a.terminate(a.ownerControl());
  assert.equal(a.doors().length, 0);
  assert.throws(() => process.kill(a.runtimePid, 0), /ESRCH/);
  const stale = await a.execute(first.view, first.plan, first.source, { ...first, subject: 'visitor', grants: grantsA });
  assert.equal(stale.record.result, 'failed');
  assert.ok(stale.record.failures.some(f => f.reason.includes('TERMINAL_INSTANCE_DEATH')));
  const candidateReceipts = [];
  for (const disposition of ['R3_HOLD', 'R3_REFUSE', 'R3_ADMIT']) candidateReceipts.push(await receiveCandidate(a.store, produced.candidate_ref, disposition));
  assert.equal(digest(a.store.get(produced.candidate_ref)), candidateBefore);
  const b = await CompositionFieldBridge.create({ root, spec: roomSpec() });
  const firstRecognition = b.recognition(a.evidence());
  const revived = await CompositionFieldBridge.create({ root, spec: roomSpec(), checkpoint });
  assert.equal(revived.instance_id, a.instance_id);
  assert.notEqual(revived.incarnation_id, a.incarnation_id);
  assert.notEqual(revived.world_id, a.world_id);
  assert.notEqual(revived.epoch, a.epoch);
  const reconstitutedDoors = revived.eligible().map(e => revived.publish(e, revived.ownerControl()));
  for (const d of reconstitutedDoors) assert.ok(![doorA.offer_id, doorB.offer_id].includes(d.offer_id));
  const newObserver = revived.observer({ anchors: [receiver.anchor], trust: true });
  const current = await routeTo(revived, newObserver, receiver, source, reconstitutedDoors[0]);
  const oldGrants = await revived.execute(current.view, current.plan, current.source, { ...current, subject: 'visitor', grants: grantsA });
  assert.equal(oldGrants.record.result, 'failed');
  const fresh = revived.authorize(current.plan, current.peers, 'visitor', revived.ownerControl());
  const newOccurrence = await revived.execute(current.view, current.plan, current.source, { ...current, subject: 'visitor', grants: fresh });
  assert.equal(newOccurrence.record.result, 'succeeded');
  const secondRecognition = b.recognition(revived.evidence());
  assert.equal(secondRecognition.parent.world_id, a.world_id);
  assert.equal(secondRecognition.same_live_authority, false);
  const recovered = recoverHistorical(a.store, a.evidence());
  assert.ok(recovered.dead); assert.throws(() => recovered.execute(), /NON_EXECUTING_REPLAY/);
  // Terminally fence every disposable process, including the independent observer instance.
  await revived.terminate(revived.ownerControl()); await b.terminate(b.ownerControl());
  const report = { schema: 'relatte.composition-instance-002-proof.experimental/v0', tested_sha: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), parents: PARENTS, normative_core_mutations: 0, instances: [a.evidence(), revived.evidence(), b.evidence()], source_anchor: receiver.anchor, source_history: receiver.history(), checkpoint, produced, candidate_receipts: candidateReceipts, recognition: [firstRecognition, secondRecognition], milestones: ['admit', 'runtime-event', 'eligible-not-routable', 'explicit-publication', 'discover-select-authorize-execute', 'fork-publish-execute', 'snapshot', 'observe-candidate-hold', 'terminal-death', 'stale-denial', 'candidate-survival', 'fresh-reconstitution', 'historical-grant-denial', 'fresh-grants-execute', 'cross-instance-recognition'], historical_prefix_ref: a.store.put(historicalA) };
  const keys = identity(), proof = signed(report, keys);
  const roots = { proof_key: keys.public_key, ledgers: report.instances.map(i => i.ledger_anchor), fields: [receiver.anchor, ...report.instances.map(i => i.field_anchor)] };
  writeFileSync(resolve(root, 'proof.json'), JSON.stringify(proof, null, 2) + '\n');
  writeFileSync(resolve(root, 'roots.json'), JSON.stringify(roots, null, 2) + '\n');
  return { proof, roots };
}
if (process.argv[1] && resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  await specimen(resolve(process.argv[2] ?? 'work/composition-instance-002'));
  console.log('Signed bridge evidence written; all disposable runtimes killed.');
}
