import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {TextEncoder} from 'node:util';
const html=fs.readFileSync(new URL('./First_Circle_001.html',import.meta.url),'utf8');
const part=html.match(/<script id="first-circle-core">([\s\S]*?)<\/script>/);
assert.ok(part,'Embedded core not found');
const context={TextEncoder};context.globalThis=context;
vm.runInNewContext(part[1],context);
const F=context.FC;
for(const s of ['', 'abc', 'The first circle', '🔥 and 差異', 'A'.repeat(200)]){
 assert.equal(F.sha256(s),crypto.createHash('sha256').update(s).digest('hex'),'SHA-256');
}
const W={id:'world-'+'a'.repeat(24),name:'Home',created:'test',parent:null};
const claim=F.createClaim(W.id,'OFFER','A bowl of soup','n-'+'a'.repeat(24),'2026-11-03',false);
let log=F.append(W,[],'PROPOSE',{claim},'t1');
assert.equal(F.derive(W,log).counts.HOLD,1);
log=F.append(W,log,'DECIDE',{id:claim.id,action:'ADMIT'},'t2');
log=F.append(W,log,'RELEASE',{id:claim.id},'t3');
const projection=F.derive(W,log);
assert.equal(projection.counts.RELEASED,1);
const packet=F.pocket(projection.cards[0],W.id,projection.head);
assert.equal(F.parsePocket(JSON.stringify(packet)).id,claim.id);
const childId='world-'+'b'.repeat(24);
const seed=F.forkSeed(W,projection.head,projection.cards,childId);
F.readSeed(seed);
const child=seed.world;
let childLog=F.append(child,[],'RECEIVE',{claim:seed.claims[0]},'t4');
assert.equal(F.derive(child,childLog).counts.HOLD,1,'Child cannot inherit admission');
childLog=F.append(child,childLog,'DECIDE',{id:claim.id,action:'REFUSE'},'t5');
assert.equal(F.derive(child,childLog).counts.REFUSE,1);
assert.equal(F.derive(W,log).counts.ADMIT,1,'Parent remains unchanged');
assert.throws(()=>F.append(W,log,'DECIDE',{id:claim.id,action:'REFUSE'},'t6'),/Conflicting disposition/);
assert.throws(()=>F.append(W,log,'PROPOSE',{claim},'t7'),/Duplicate claim/);
assert.equal(F.derive(W,JSON.parse(JSON.stringify(log))).head,projection.head,'Deterministic replay');
let tampered=JSON.parse(JSON.stringify(log));tampered[0].payload.claim.text+='tampered';
assert.throws(()=>F.derive(W,tampered),/Hash mismatch/);
const paradox=F.paradox();
assert.equal(paradox.b.cards[0].status,'ADMIT');
assert.equal(paradox.c.cards[0].status,'REFUSE');
assert.notEqual(paradox.b.stateHash,paradox.c.stateHash);
assert.ok(html.includes('id="boot-data"'));
assert.ok(html.includes("'card-list','proof-feedback'"), 'Child export must scrub live DOM content');
console.log('PASS: SHA-256 fixtures, replay, tamper rejection, idempotence gate, admission boundaries, child non-inheritance, packet validation, divergent worlds.');
